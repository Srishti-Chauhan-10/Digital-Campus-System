function solveMath(text) {
  const t = text.replace(/\s+/g, ' ');

  // 1) દ્વિચલ સુરેખ સમીકરણ : "3x + 5 = 20"  કે  "2x - 7 = 3x + 2"
  const eq = t.match(/([-+]?\d*\.?\d*)\s*([xyXY])\s*([-+]\s*\d+\.?\d*)?\s*=\s*([-+]?\d*\.?\d*)\s*([xyXY])?\s*([-+]\s*\d+\.?\d*)?/);
  if (eq && /[xXyY]/.test(t)) {
    const a1 = eq[1] === '' ? 1 : (eq[1] === '-' ? -1 : parseFloat(eq[1]));
    const c1 = parseFloat((eq[3] || '0').replace(/\s/g, '')) || 0;
    const hasVar2 = !!eq[5];
    const a2 = hasVar2 ? (parseFloat(eq[4] || '0') || 0) : 0;
    const c2 = hasVar2 ? (parseFloat((eq[6] || '0').replace(/\s/g, '')) || 0)
      : (parseFloat((eq[4] || '0').replace(/\s/g, '')) || 0);
    const d = c1 - c2;
    const k = a1 - a2;
    if (k !== 0) {
      const x = d / k;
      return {
        text: `સમીકરણ : ${eq[0].trim()}\n\nઉકેલ :\n(${a1})x ${c1 >= 0 ? '+' : '–'} ${Math.abs(c1)} = (${a2 === 0 ? '0' : a2})x ${c2 >= 0 ? '+' : '–'} ${Math.abs(c2)}\n(${a1} – ${a2})x = ${c1} – ${c2}\n${k}x = ${d}\nx = ${d} ÷ ${k} = ${Number(x.toFixed(4))}\n\nચકાસણી કરીને જવાબ સાચો છે તે ચકાસો.`,
        chapter: 4,
      };
    }
  }

  const nums = [...new Set((t.match(/\d+(?:\.\d+)?/g) || []).map(Number))];

  // 2) હેરોન : ત્રિકોણનું ક્ષેત્રફળ
  if (/ત્રિકોણ|triangle/i.test(t) && nums.length >= 3) {
    const [a, b, c] = nums.slice(0, 3).sort((p, q) => p - q);
    if (a + b > c) {
      const s = (a + b + c) / 2;
      const area = Math.sqrt(Math.max(0, s * (s - a) * (s - b) * (s - c)));
      if (area > 0) {
        return {
          text: `હેરોનના સૂત્રથી :\nભુજા a = ${a}, b = ${b}, c = ${c}\nઅર્ધપરિધાન s = (${a}+${b}+${c}) ÷ 2 = ${s}\nક્ષેત્રફળ = √[${s} × ${s - a} × ${s - b} × ${s - c}]\nક્ષેત્રફળ = ${Number(area.toFixed(3))} ચોમાં`,
          chapter: 10,
        };
      }
    }
  }

  // 3) પાઇથાગોરસ
  if (/પાઇથાગોરસ|pythagoras|કર્ણ|hypotenuse|વિકલ/i.test(t) && nums.length >= 2) {
    const [x, y] = nums.slice(0, 2);
    const z = Math.sqrt(x * x + y * y);
    return {
      text: `પાઇથાગોરસ : a² + b² = c²\nઆધાર = ${x}, ઊંચાઈ = ${y}\nકર્ણ = √(${x}² + ${y}²) = √${x * x + y * y} = ${Number(z.toFixed(3))}`,
      chapter: 3,
    };
  }

  // 4) સરેરાશ
  if (/સરેરાશ|માધ્યક|average/i.test(t) && nums.length >= 2) {
    const s = nums.reduce((p, q) => p + q, 0);
    return {
      text: `સરેરાશ = કુલ યોગ ÷ સંખ્યા\nકુલ = ${nums.join(' + ')} = ${s}\nસરેરાશ = ${s} ÷ ${nums.length} = ${Number((s / nums.length).toFixed(3))}`,
      chapter: 12,
    };
  }

  // 5) વર્તુળ
  if (/વર્તુળ|circle|ઘેરાફળ|π/i.test(t) && nums.length >= 1) {
    const r = nums[0];
    return {
      text: `ત્રિજ્યા r = ${r}\n• ક્ષેત્રફળ = π r² = (22/7) × ${r}² = ${Number(((22 / 7) * r * r).toFixed(3))} ચો.મા.\n• ઘેરાફળ = 2 π r = 2 × (22/7) × ${r} = ${Number(((44 / 7) * r).toFixed(3))} મા.`,
      chapter: 9,
    };
  }

  return null;
}


/**
 * મુખ્ય પ્રવાહ : વિદ્યાર્થીનો પ્રશ્ન → ચોકસાઈ સાથે જવાબ
 */
export function answerDoubt({ question, std, subjectHint }) {
  const q = (question || '').trim();
  if (!q) {
    return {
      answer: 'પ્રશ્ન લખો નહીં તો હું મદદ કરી શકું નહીં.',
      subject: null, chapter: null, confidence: 0, solved: false,
      source: 'none', needTeacher: true,
    };
  }

  const subject = detectSubject(q, subjectHint);
  const low = q.toLowerCase();
  let best = null;

  // 1) ગણિત સોલ્વર (સૌથી ચોકસાઈ)
  if (subject === 'MATH' || (/[0-9]/.test(q) && /[=+\-×÷*/²√π]/.test(q))) {
    const solved = solveMath(q);
    if (solved) {
      return {
        answer: solved.text,
        subject: 'MATH', chapter: solved.chapter, confidence: 0.95,
        solved: true, source: 'ગણિત સૂત્ર (ચોકસ પરિણામ)',
        needTeacher: false,
      };
    }
  }

  // 2) જ્ઞાનભંડોલ — પહેલા તમારા ધોરણ પ્રમાણે, પછી અન્ય ધોરણનો સામાન્ય જવાબ
  let relaxed = false;
  const search = (allowOtherStd) => {
    let b = null;

    for (const e of KB) {
      if (subject && e.code !== subject) continue;
      if (e.s && e.s !== std && !allowOtherStd) continue;
      let hits = 0;
      for (const k of e.kw) {
        const kk = String(k).toLowerCase();
        if (low.includes(kk)) hits += kk.length >= 4 ? kk.length : 1;
      }
      if (hits > 0 && (!b || hits > b.hits)) b = { ...e, hits };
    }

    // 2b) પ્રકરણ-સ્તરીય ખોલ પાત્ર (અભ્યાસક્રમ પ્રકારનો જવાબ)
    let chap = null;
    for (const c of CHAPTER_INTRO) {
      if (subject && c.c !== subject) continue;
      if (c.s && c.s !== std && !allowOtherStd) continue;
      for (const k of c.k) {
        const kk = String(k).toLowerCase();
        if (low.includes(kk)) {
          const score = kk.length >= 4 ? kk.length : 1;
          if (!chap || score > chap.hits) chap = { ...c, hits: score };
          break;
        }
      }
    }
    if (chap && (!b || chap.hits >= b.hits)) {
      b = { code: chap.c, ch: chap.ch, a: chap.a, hits: chap.hits, fromChapters: true };
    }
    return b;
  };

  best = search(false);
  if (!best) { best = search(true); relaxed = !!best; }

  if (best) {
    const conf = Math.min(0.92, 0.55 + best.hits * 0.02) - (relaxed ? 0.1 : 0);
    const src = relaxed
      ? `${SUBJECT_GU[best.code] || best.code} — સામાન્ય જવાબ`
      : (best.ch
        ? `${SUBJECT_GU[best.code] || best.code} — પ્રકરણ ${best.ch} (ધોરણ ${std})`
        : `${SUBJECT_GU[best.code] || best.code} (ધોરણ ${std})`);
    return {
      answer: best.a,
      subject: best.code, chapter: relaxed ? null : (best.ch || null),
      confidence: Number(Math.max(0.4, conf).toFixed(2)), solved: true,
      source: src, needTeacher: false,
    };
  }

  // 3) ચોકસાઈ વગર જવાબ આપવો નહીં — શિક્ષક પાસે મોકલો
  return {
    answer:
      'આ પ્રશ્નનો ચોકસાઈ પૂરો જવાબ મારા પાસે ઉપલબ્ધ અભ્યાસક્રમ જ્ઞાનમાં નથી.\n' +
      'એટલે હું અંદાજ લગાવીને ખોટો જવાબ આપવાનું ટાળું છું. તમારો પ્રશ્ન શિક્ષકને મોકલી દીધો છે — તરત જ જવાબ મળશે.\n\n' +
      'સૂચવો : પ્રશ્નમાં વિષય, પ્રકરણ નંબર અને પૂરો પ્રશ્ન લખો હોય તો વધુ ઝડપથી મદદ મળશે.',
    subject, chapter: null, confidence: 0, solved: false,
    source: 'શિક્ષક પાસે મોકલાયેલ',
    needTeacher: true,
  };
}

